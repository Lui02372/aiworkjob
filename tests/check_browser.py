"""Real source smoke test + isolated fixture UI workflows; never submits an external application."""
import json,time,os
from pathlib import Path
from playwright.sync_api import sync_playwright,expect

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'artifacts'
OUT.mkdir(exist_ok=True)
checks=[]
base=os.environ.get('AIWORKJOB_TEST_URL','http://127.0.0.1:8787').rstrip('/')
def check(name,condition=True):
    assert condition,name
    checks.append(name)

raw={"title":"TEST Content Creator","companyName":"UI test fixture only","guid":"https://himalayas.app/companies/test/jobs/content-creator","applicationLink":"https://himalayas.app/companies/test/jobs/content-creator?utm_source=api","excerpt":"Test editorial work.","description":"Content editing. No AI experience is required.","employmentType":"Contractor","locationRestrictions":[],"timezoneRestrictions":[9],"expiryDate":int(time.time())+86400,"pubDate":int(time.time()),"salaryPeriod":"hourly","minSalary":20,"maxSalary":30,"currency":"USD"}
fixture={"jobs":[raw],"fetchedAt":int(time.time()*1000),"country":"South Korea","partial":False}

with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,channel='chrome')
    live=browser.new_context(viewport={"width":1440,"height":1050})
    page=live.new_page();errors=[]
    page.on('pageerror',lambda err:errors.append(str(err)))
    page.goto(base,wait_until='networkidle')
    expected_version=json.loads((ROOT/'package.json').read_text(encoding='utf-8'))['version']
    assert page.evaluate("async()=>{const c=await import('./config.js');return c.APP_VERSION}")==expected_version,'browser server is not the current B version'
    page.wait_for_selector('.job-card',timeout=35000)
    check('real source jobs appear',page.locator('.job-card').count()>0)
    check('list is paginated',page.locator('.job-card').count()<=12)
    page.screenshot(path=str(OUT/'desktop.png'))
    page.set_viewport_size({"width":390,"height":844})
    check('mobile layout has no horizontal overflow',page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
    page.screenshot(path=str(OUT/'mobile.png'))
    check('real source UI has no JavaScript errors',not errors)
    live.close()

    context=browser.new_context(viewport={"width":1440,"height":1000})
    context.route('**/api/jobs?**',lambda route:route.fulfill(json=fixture))
    context.route('**/api/check?**',lambda route:route.fulfill(json={"status":"open","job":raw}))
    page=context.new_page();errors=[]
    page.on('pageerror',lambda err:errors.append(str(err)))
    page.goto(base,wait_until='networkidle')
    expect(page.locator('.job-card')).to_have_count(1)
    page.locator('#search').fill('missing-9876')
    expect(page.locator('.empty-state')).to_be_visible()
    page.get_by_role('button',name='검색 조건 초기화').click()
    check('search and empty state recover',page.locator('.job-card').count()==1)
    page.get_by_role('button',name='일감 저장',exact=True).click()
    page.locator('.sidebar a[href="#saved"]').click()
    page.reload(wait_until='networkidle')
    expect(page.locator('.job-card')).to_have_count(1)
    check('saved jobs survive reload')
    page.locator('.side-nav a[href="#home"]').click()
    page.locator('.hero [data-action="match"]').click()
    expect(page.locator('#profile-form')).to_be_visible()
    page.locator('#profile-name').fill('테스트 메이커')
    page.locator('#years').fill('5')
    page.locator('#profile-level').select_option('전문')
    page.locator('[name="english"]').check()
    page.locator('#bio').fill('I have reviewed and edited original content for five years.')
    page.get_by_role('button',name='프로필 저장').click()
    expect(page.locator('.match-result')).to_be_visible()
    check('one click matching uses saved conditions')
    page.get_by_role('button',name='요건 확인하고 수락하기').click()
    expect(page.locator('#dialog-title')).to_have_text('일감 자세히 보기')
    check('original application URL is preserved',page.locator('#dialog .button.outline').get_attribute('href')==raw['applicationLink'])
    page.locator('[data-action="accept"]').click()
    expect(page.locator('#accept-error')).to_contain_text('필수 조건')
    check('accept requires explicit requirement review')
    page.locator('#accept-confirm').check()
    page.locator('[data-action="accept"]').click()
    page.wait_for_url('**/#workspace/*')
    expect(page.locator('#policy-form')).to_be_visible()
    check('accept creates one workspace and does not mark applied',page.locator('.progress-stage.current').count()==1)
    check('AI creation locked before permission',page.locator('#builder-form').count()==0 and page.locator('.link-grid a').count()==0)
    page.locator('#policy').select_option('allowed')
    page.get_by_role('button',name='조건 저장',exact=True).click()
    expect(page.locator('#policy-form .form-error')).to_contain_text('10자')
    page.locator('#policy-note').fill('TEST ONLY: client permits tools on public editorial content. No client data.')
    page.get_by_role('button',name='조건 저장',exact=True).click()
    expect(page.locator('#builder-form')).to_be_visible()
    check('permission evidence unlocks creator')
    page.get_by_role('button',name='지원 초안 채우기').click()
    check('application draft has truthful experience', 'five years' in page.locator('#proposal').input_value())
    page.get_by_role('button',name='지원 메시지 저장',exact=True).click()
    page.reload(wait_until='networkidle')
    check('workspace and application draft persist','five years' in page.locator('#proposal').input_value())
    page.locator('#template').select_option('app')
    page.locator('#draft-title').fill('검토용 <script>window.injected=1</script>')
    page.locator('#draft-intro').fill('작업 흐름을 직접 확인하는 테스트용 앱 화면입니다.')
    page.locator('#draft-body').fill('요구사항 확인\n실제 사용 목적과 동작을 확인합니다.\n\n동작 검증\n입력과 저장, 완료 상태를 검토합니다.')
    page.get_by_role('button',name='제작 페이지 만들기').click()
    preview_href=page.get_by_role('link',name='제작 화면 미리보기').get_attribute('href')
    preview=context.new_page();preview.goto(preview_href,wait_until='networkidle')
    expect(preview.locator('h1')).to_contain_text('<script>')
    check('generated page cannot execute input HTML',preview.evaluate('typeof window.injected')=='undefined')
    preview.locator('#task-input').fill('검증용 작업')
    preview.locator('#task-form button').click()
    preview.locator('#tasks input').check()
    preview.reload(wait_until='networkidle')
    expect(preview.locator('#tasks input')).to_be_checked()
    check('generated app task interaction persists')
    preview.screenshot(path=str(OUT/'deliverable.png'))
    preview.goto(base+'/deliverable.html#broken')
    expect(preview.locator('.error')).to_be_visible()
    check('invalid shared page links fail with recovery direction')
    preview.close()
    studio_href=page.get_by_role('link',name='업무별 작업 스튜디오 열기').get_attribute('href')
    studio=context.new_page();studio.goto(studio_href,wait_until='networkidle')
    studio.locator('#add-row').click()
    studio.locator('#row-title').fill('콘텐츠 주제 1')
    studio.locator('#row-context').fill('뉴스레터 / 입문 독자')
    studio.locator('#row-body').fill('사실관계와 원문 출처를 직접 열어 확인한 콘텐츠입니다.')
    studio.locator('#row-source').fill('https://example.com/source')
    studio.locator('#edit-status').select_option('reviewed')
    studio.get_by_role('button',name='작업 항목 저장').click()
    studio.reload(wait_until='networkidle')
    expect(studio.locator('.studio-row')).to_have_count(1)
    check('job specific studio saves editable evidence')
    studio.locator('#publish-preview').click()
    expect(studio.locator('#studio-message')).to_contain_text('공개 자료')
    studio.locator('#public-content').check()
    studio.locator('#publish-preview').click()
    expect(studio.get_by_role('link',name='결과물 화면 열기')).to_be_visible()
    check('studio result sharing requires content confirmation')
    studio.screenshot(path=str(OUT/'studio.png'))
    studio.close()
    page.get_by_role('button',name='지원 제출 기록하기',exact=True).click()
    page.evaluate("(()=>{window.originalSetItem=Storage.prototype.setItem;Storage.prototype.setItem=function(){throw new DOMException('quota','QuotaExceededError')};})()")
    page.get_by_role('button',name='확인한 사실 기록하기').click()
    expect(page.locator('#dialog')).to_be_visible()
    expect(page.locator('#toast')).to_contain_text('저장하지 못했습니다')
    check('quota failure does not advance status or close confirmation',page.locator('.progress-stage.current').count()==1)
    page.evaluate('(()=>{Storage.prototype.setItem=window.originalSetItem;})()')
    page.locator('#dialog [data-action="close"]').first.click()
    for label in ['지원 제출 기록하기','계약 확인 기록하기']:
        page.get_by_role('button',name=label,exact=True).click()
        page.get_by_role('button',name='확인한 사실 기록하기').click()
        expect(page.locator('#dialog')).not_to_be_visible()
    page.get_by_role('button',name='납품 기록하기',exact=True).click()
    page.get_by_role('button',name='확인한 사실 기록하기').click()
    expect(page.locator('#status-error')).to_contain_text('HTTPS')
    page.locator('#dialog [data-action="close"]').first.click()
    check('delivery status requires real HTTPS URL record')
    page.locator('#delivery').fill('https://example.com/fixture-result')
    page.locator('#amount').fill('100')
    page.locator('#currency').select_option('USD')
    page.get_by_role('button',name='납품·입금 정보 저장').click()
    for label in ['납품 기록하기','입금 확인 기록하기']:
        page.get_by_role('button',name=label,exact=True).click()
        page.get_by_role('button',name='확인한 사실 기록하기').click()
        expect(page.locator('#dialog')).not_to_be_visible()
    expect(page.locator('.progress-stage.current')).to_have_count(5)
    check('workflow records application contract delivery payment separately',page.locator('.progress-stage.current').count()==5)
    workspace_hash=page.evaluate('location.hash')
    page.locator('.sidebar a[href="#earnings"]').click()
    expect(page.locator('main')).to_contain_text('USD 100')
    expect(page.locator('main')).to_contain_text('인출 가능한 잔액이 아닙니다')
    check('income ledger shows currency separated self reports')
    page.goto(base+'/'+workspace_hash,wait_until='networkidle')
    original=page.locator('#proposal').input_value()
    page.evaluate("(()=>{window.originalSetItem=Storage.prototype.setItem;Storage.prototype.setItem=function(){throw new DOMException('quota','QuotaExceededError')};})()")
    page.locator('#proposal').fill('Unsaved quota regression')
    page.get_by_role('button',name='지원 메시지 저장',exact=True).click()
    expect(page.locator('#storage-warning')).to_be_visible()
    expect(page.locator('#toast')).to_contain_text('저장하지 못했습니다')
    check('quota failure preserves pending text without updating the saved proposal',page.locator('#proposal').input_value()=='Unsaved quota regression' and page.evaluate("JSON.parse(localStorage.getItem('aiworkjob.live.v1')).workspaces[0].proposal")==original)
    page.evaluate('(()=>{Storage.prototype.setItem=window.originalSetItem;})()')
    page.screenshot(path=str(OUT/'workspace.png'))
    page.locator('#policy').select_option('prohibited')
    page.get_by_role('button',name='조건 저장',exact=True).click()
    expect(page.locator('#builder-form')).to_have_count(0)
    check('prohibited status locks tools prompts and past preview links',page.locator('#builder-form').count()==0 and page.locator('#work-prompt').count()==0 and page.get_by_role('link',name='제작 화면 미리보기').count()==0 and page.locator('.link-grid a').count()==0)
    page.locator('.side-nav a[href="#home"]').click()
    pending=[]
    context.unroute('**/api/jobs?**')
    context.route('**/api/jobs?**',lambda route:pending.append(route))
    with page.expect_request('**/api/jobs?**'):
        page.get_by_role('button',name='다시 확인',exact=True).click()
    page.locator('.side-nav a[href="#profile"]').click()
    page.locator('#profile-name').fill('Unsaved form remains')
    with page.expect_response('**/api/jobs?**'):
        pending[0].fulfill(json=fixture)
    page.evaluate('()=>new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))')
    expect(page.locator('#profile-name')).to_have_value('Unsaved form remains')
    check('background source refresh preserves unsaved form input')
    check('fixture UI has no JavaScript errors',not errors)
    context.close()
    browser.close()

report={'status':'passed','checkedAt':time.strftime('%Y-%m-%dT%H:%M:%S'),'checks':checks,'count':len(checks),'fixtureTests':'Isolated browser context; no actual job application, contract or money movement.'}
